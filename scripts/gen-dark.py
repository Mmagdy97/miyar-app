#!/usr/bin/env python3
"""Generate src/dark.css: html.dark overrides for every colour utility used in src/**/*.jsx."""
import re, glob, colorsys, math, sys, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def oklch_to_hex(L,C,h):
    a=C*math.cos(math.radians(h)); b=C*math.sin(math.radians(h))
    l_=L+0.3963377774*a+0.2158037573*b; m_=L-0.1055613458*a-0.0638541728*b; s_=L-0.0894841775*a-1.2914855480*b
    l,m,s=l_**3,m_**3,s_**3
    r=4.0767416621*l-3.3077115913*m+0.2309699292*s
    g=-1.2684380046*l+2.6097574011*m-0.3413193965*s
    bl=-0.0041960863*l-0.7034186147*m+1.7076147010*s
    def f(x):
        x=max(0,min(1,x)); x=12.92*x if x<=0.0031308 else 1.055*x**(1/2.4)-0.055
        return round(x*255)
    return '#%02x%02x%02x'%(f(r),f(g),f(bl))
PAL={}
for m in re.finditer(r'--color-([a-z]+-\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)',open(ROOT+'/node_modules/tailwindcss/theme.css').read()):
    PAL[m.group(1)]=oklch_to_hex(float(m.group(2))/100,float(m.group(3)),float(m.group(4)))
PAL['white']='#ffffff'; PAL['black']='#000000'

def hex2rgb(h):
    h=h.lstrip('#')
    if len(h)==3: h=''.join(c*2 for c in h)
    return tuple(int(h[i:i+2],16) for i in (0,2,4))
def rgb2hex(r,g,b): return '#%02x%02x%02x'%(round(r),round(g),round(b))
def hsl(h):
    r,g,b=[x/255 for x in hex2rgb(h)]; H,L,S=colorsys.rgb_to_hls(r,g,b); return H,S,L
def fromhsl(H,S,L):
    r,g,b=colorsys.hls_to_rgb(H,max(0,min(1,L)),max(0,min(1,S))); return rgb2hex(r*255,g*255,b*255)

ACCENT='#e0714f'
# explicit neutral map (light-theme brand colours -> dark theme)
BG={'#faf7f0':'#10172a','#ffffff':'#151d33','#fff':'#151d33','#f3efe6':'#0c1120','#faf7f0':'#10172a','#ecf0f1':'#1b2540','#e9e3d5':'#1b2540','#dad3c2':'#273250',
    '#24304d':ACCENT,'#1a2236':'#9a3822','#b5452b':ACCENT}
TEXT={'#1a2236':'#e9e3d5','#24304d':'#e9e3d5','#535e78':'#a1a9bd','#65708a':'#8a93a8','#ffffff':'#ffffff','#fff':'#ffffff','#b5452b':'#f0987a'}
BORDER={'#dad3c2':'#273250','#e9e3d5':'#1d2744','#c6beaa':'#33405F','#ffffff':'#273250','#24304d':'#3e4b6c','#b5452b':ACCENT}

def dark(prop,hexv,alpha_=False):
    h=hexv.lower()
    if prop in('bg','from','to','via'):
        H,S,L=hsl(h)
        if alpha_ and S<0.2 and L<0.3: return '#000000'
        if h in BG: return BG[h]
        if S<0.12:   # neutral
            return fromhsl(0.62,0.12,0.06+ (1-L)*0.16) if L>0.5 else h
        if L>0.8: return fromhsl(H,min(S,0.45),0.13)
        if L>0.55: return fromhsl(H,min(S,0.5),0.2)
        return h
    if prop in('text','fill','stroke','decoration','caret','accent'):
        if h in TEXT: return TEXT[h]
        H,S,L=hsl(h)
        if S<0.15: return fromhsl(H,0.08,1-L*0.9) if L<0.55 else h
        return fromhsl(H,min(1,S),0.68) if L<0.5 else h
    # border / ring / divide / outline / shadow
    if h in BORDER: return BORDER[h]
    H,S,L=hsl(h)
    if S<0.12: return fromhsl(0.62,0.1,0.09+(1-L)*0.14) if L>0.5 else h
    if L>0.7: return fromhsl(H,min(S,0.4),0.26)
    return h

def rgba(hexv,alpha):
    r,g,b=hex2rgb(hexv); return 'rgb(%d %d %d / %s)'%(r,g,b,alpha)

CSSPROP={'bg':'background-color','text':'color','border':'border-color','ring':'--tw-ring-color','from':'--tw-gradient-from','to':'--tw-gradient-to','via':'--tw-gradient-via',
         'divide':'border-color','fill':'fill','stroke':'stroke','outline':'outline-color','decoration':'text-decoration-color','accent':'accent-color','caret':'caret-color','shadow':'--tw-shadow-color'}
TOKEN=re.compile(r'((?:(?:hover|focus|active|disabled|group-hover|placeholder|focus-within|focus-visible|sm|md|lg|xl|ltr|rtl):)*)(bg|text|border|ring|from|to|via|divide|fill|stroke|outline|decoration|accent|caret|shadow)-(\[#[0-9A-Fa-f]{3,8}\]|white|black|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3})(?:/(\d+))?(?![\w-])')
MQ={'sm':640,'md':768,'lg':1024,'xl':1280}
def esc(c): return re.sub(r'([^a-zA-Z0-9_-])',r'\\\1',c)

seen={}; 
for f in glob.glob(ROOT+'/src/**/*.jsx',recursive=True)+[ROOT+'/index.html']:
    for m in TOKEN.finditer(open(f,encoding='utf8').read()):
        seen[m.group(0)]=m.groups()
out=['/* GENERATED by scripts/gen-dark.py — do not edit. Dark theme overrides for colour utilities. */']
rules=[]
for cls,(pre,prop,col,alpha) in sorted(seen.items()):
    if col.startswith('[#'):
        hx=col[1:-1]
        if len(hx)==8: hx='#'+hx[1:7]
    else:
        hx=PAL.get(col)
        if not hx: continue
    if prop=='text' and hx.lower() in ('#ffffff','#fff') : continue
    if prop=='bg' and hx.lower()=='#000000': continue
    d=dark(prop,hx,bool(alpha))
    val=rgba(d,int(alpha)/100) if alpha else d
    sel='html.dark .'+esc(cls)
    variants=[v for v in pre.split(':') if v]
    mq=None; pseudo=''; grp=False; dirv=None
    for v in variants:
        if v in MQ: mq=MQ[v]
        elif v in('hover','focus','active','disabled','focus-within','focus-visible'): pseudo=':'+v
        elif v=='placeholder': pseudo='::placeholder'
        elif v=='group-hover': grp=True
        elif v in('ltr','rtl'): dirv=v
    if grp: sel='html.dark .group:hover '+'.'+esc(cls)
    else: sel+=pseudo
    if dirv: sel='html.dark [dir=%s] '%dirv+sel[len('html.dark '):]
    decl='%s:%s'%(CSSPROP[prop],val)
    rule='%s{%s}'%(sel,decl)
    rules.append((mq,rule))
base=[r for q,r in rules if q is None]
out+=base
for q in sorted({q for q,_ in rules if q}):
    out.append('@media (min-width:%dpx){%s}'%(q,''.join(r for qq,r in rules if qq==q)))
open(ROOT+'/src/dark.css','w').write('\n'.join(out)+'\n')
print(len(rules),'rules')
